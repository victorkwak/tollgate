//! nextest tool config and filtersets (R36, R58, R72).
//!
//! tollgate passes `--tool-config-file tollgate:<generated>` with profiles
//! `tollgate-fast` and `tollgate-full`: retries, slow and global timeouts,
//! the JUnit path, and the `pg` test group (`max-threads` from the host
//! config) assigned to `select.fast.pg_tests`. The repo's
//! `.config/nextest.toml` from the policy commit (R49) has higher priority.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::config::Tier;
use crate::config::host::NextestHost;
use crate::config::repo::FastTests;

/// Name of the nextest profile of `tier`.
#[must_use]
pub fn profile(tier: Tier) -> String {
    format!("tollgate-{tier}")
}

/// The test group of the `pg` resource. Tool groups must carry the tool
/// prefix (nextest refuses others).
pub const PG_GROUP: &str = "@tool:tollgate:pg";

/// The JUnit file name inside `<target>/nextest/<profile>/`.
pub const JUNIT_FILE: &str = "junit.xml";

fn is_plain(s: &str) -> bool {
    !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// The filterset of `select.fast.pg_tests`: `<package>::*` names every
/// binary of a package (its unit tests too); any other entry is a
/// binary-id glob.
#[must_use]
pub fn pg_filter(pg_tests: &[String]) -> Option<String> {
    let parts: Vec<String> = pg_tests
        .iter()
        .map(|t| match t.strip_suffix("::*") {
            Some(pkg) if is_plain(pkg) => format!("package(={pkg})"),
            _ => format!("binary_id({t})"),
        })
        .collect();
    (!parts.is_empty()).then(|| parts.join(" | "))
}

/// The generated tool config (R72).
#[must_use]
pub fn tool_config(host: &NextestHost, pg_tests: &[String]) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# Generated by tollgate (R72). The repo's .config/nextest.toml overrides it.\n"
    );
    let _ = writeln!(
        s,
        "[test-groups]\n\"{PG_GROUP}\" = {{ max-threads = {} }}\n",
        host.pg_max_threads
    );
    let pg = pg_filter(pg_tests);
    for tier in [Tier::Fast, Tier::Full] {
        let p = profile(tier);
        let global = match tier {
            Tier::Fast => &host.global_timeout_fast,
            Tier::Full => &host.global_timeout_full,
        };
        let _ = writeln!(
            s,
            "[profile.{p}]\nretries = {}\nfail-fast = false\nslow-timeout = {{ period = \"{}s\", terminate-after = {} }}\nglobal-timeout = \"{}s\"\n\n[profile.{p}.junit]\npath = \"{JUNIT_FILE}\"\n",
            host.retries,
            host.slow_timeout.get().as_secs().max(1),
            host.terminate_after,
            global.get().as_secs().max(1),
        );
        if let Some(f) = &pg {
            let _ = writeln!(
                s,
                "[[profile.{p}.overrides]]\nfilter = '{f}'\ntest-group = \"{PG_GROUP}\"\n"
            );
        }
    }
    s
}

fn any_of(func: &str, names: &BTreeSet<String>) -> String {
    let parts: Vec<String> = names.iter().map(|n| format!("{func}(={n})")).collect();
    format!("({})", parts.join(" | "))
}

/// The fast-tier filterset (R58) for the marked packages, or `None` when
/// nothing is marked.
///
/// - `rdeps-all`: `rdeps(a) | rdeps(b)`.
/// - `rdeps-unit+changed-integration`:
///   `(rdeps(a)|rdeps(b)) & !kind(test) | (package(a)|package(b)) & kind(test)`.
#[must_use]
pub fn filterset(mode: FastTests, marked: &BTreeSet<String>) -> Option<String> {
    if marked.is_empty() {
        return None;
    }
    let rdeps = any_of("rdeps", marked);
    Some(match mode {
        FastTests::RdepsAll => rdeps,
        FastTests::RdepsUnitChangedIntegration => format!(
            "({rdeps} & !kind(test)) | ({} & kind(test))",
            any_of("package", marked)
        ),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn set(names: &[&str]) -> BTreeSet<String> {
        names.iter().map(|s| (*s).to_owned()).collect()
    }

    #[test]
    fn filtersets_r58() {
        assert_eq!(
            filterset(FastTests::RdepsAll, &set(&["a", "b"])).unwrap(),
            "(rdeps(=a) | rdeps(=b))"
        );
        assert_eq!(
            filterset(FastTests::RdepsUnitChangedIntegration, &set(&["a"])).unwrap(),
            "((rdeps(=a)) & !kind(test)) | ((package(=a)) & kind(test))"
        );
        assert_eq!(filterset(FastTests::RdepsAll, &BTreeSet::new()), None);
    }

    #[test]
    fn tool_config_has_both_profiles_and_the_pg_group_r72() {
        let host = NextestHost::default();
        let text = tool_config(&host, &["gatehouse-api::*".into(), "core::db_*".into()]);
        assert!(text.contains("[profile.tollgate-fast]"), "{text}");
        assert!(text.contains("[profile.tollgate-full]"), "{text}");
        assert!(text.contains("retries = 2"), "{text}");
        assert!(text.contains("\"@tool:tollgate:pg\" = { max-threads = 12 }"));
        assert!(text.contains("global-timeout = \"900s\""), "{text}");
        assert!(text.contains("global-timeout = \"6000s\""), "{text}");
        assert!(
            text.contains("filter = 'package(=gatehouse-api) | binary_id(core::db_*)'"),
            "{text}"
        );
        let parsed: toml::Table = toml::from_str(&text).unwrap();
        assert!(parsed.contains_key("profile"));
        assert!(!tool_config(&host, &[]).contains(".overrides]]"));
    }
}
